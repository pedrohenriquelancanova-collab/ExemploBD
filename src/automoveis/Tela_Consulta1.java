    private void carregarTabela(){

    try{
        String sql = "SELECT * FROM Automovel";
        PreparedStatement ps = conexao.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        DefaultTableModel model = (DefaultTableModel) tabelaConsulta.getModel();

        // Limpa todos os registros anteriores da tabela
        model.setRowCount(0);

        // Percorre os registros retornados pelo banco
        while(rs.next()){

            model.addRow(new Object[]{
                rs.getString("ID"),
                rs.getString("Marca"),
                rs.getString("Modelo"),
                rs.getString("Placa"),
                rs.getString("Cor")
            });

        }

        rs.close();
        ps.close();

    }catch (Exception e){
        System.out.println("Erro ao efetuar consulta no BD: " + e.getMessage());
    }
}

